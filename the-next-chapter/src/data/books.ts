export function getBookBySlug(slug: string): Book | undefined {
  return books.find((book) => book.slug === slug);
}

export function getFeaturedBooks(): Book[] {
  return books.filter((book) => book.featured);
}

export function getAuthorSpotlight(): Book | undefined {
  return books.find((book) => book.authorSpotlight);
}

export function getRelatedBooks(book: Book, limit = 3): Book[] {
  return books
    .filter(
      (b) =>
        b.slug !== book.slug &&
        (b.genre === book.genre ||
          b.ageRange === book.ageRange ||
          b.interests.some((i) => book.interests.includes(i)))
    )
    .slice(0, limit);
}
